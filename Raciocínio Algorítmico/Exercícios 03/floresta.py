def perguntar_opcao(pergunta, opcoes_validas):
    while True:
        resposta = input(pergunta).strip().lower()
        if resposta in opcoes_validas:
            return resposta
        print(f"Opção inválida! Digite uma destas: {', '.join(opcoes_validas)}.\n")

escolha = perguntar_opcao(
    "Você está em uma floresta e precisa escolher um caminho para seguir.\n"
    "Você pode escolher: esquerda ou direita: ",
    ["esquerda", "direita"]
)

if escolha == "esquerda":
    print("\nVocê encontrou um RIO! Você pode atravessá-lo ou voltar. O que você escolhe?")
    escolha_rio = perguntar_opcao(
        "Digite 'atravessar' para atravessar o rio ou 'voltar' para voltar: ",
        ["atravessar", "voltar"]
    )

    if escolha_rio == "atravessar":
        print("\nVocê chegou em uma vila segura com muita cerveja e comida! Good ending!")
    else:
        print("\nVocê permanece perdido na floresta. Bad ending!")

elif escolha == "direita":
    print("\nVocê encontrou uma montanha! Você pode escolher: subir ou voltar.")
    escolha_montanha = perguntar_opcao(
        "Digite 'subir' para escalá-la ou 'voltar' para retornar à floresta: ",
        ["subir", "voltar"]
    )

    if escolha_montanha == "subir":
        print("\nVocê escalou a montanha e encontrou um tesouro! Good ending!")
    else:
        print("\nVocê volta para a floresta e continua perdido. Bad ending!")